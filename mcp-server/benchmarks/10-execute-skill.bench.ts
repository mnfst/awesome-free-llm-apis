  const extractedFiles = extractReferencedFiles(SAMPLE_SKILL_MD);
  const sampleSkillTokens = countTokens(SAMPLE_SKILL_MD);
  const combinedTokens = countTokens(HERMES_ADAPTER_NOTE + SAMPLE_SKILL_MD);

