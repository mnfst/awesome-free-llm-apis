import { bench, describe } from "vitest";
import { getIntelligentSystemPrompt } from "../src/pipeline/middlewares/prompts.js";
import { ShortTermMemory } from "../src/memory/short-term.js";
import { executeInSandbox } from "../src/sandbox/executor.js";
import { countTokens } from "./helpers/token-counter.js";
import { writeBenchmarkLog } from "./helpers/log-writer.js";

// Ensure benchmark output log is populated
generateLogReport().catch(console.error);

describe("01-pipeline benchmarks", () => {
  // Scenario 1: Prompt Injection
  bench("Prompt Injection (Intelligent System Prompt)", async () => {
    const prompt = await getIntelligentSystemPrompt({
      context: "Review python code and check memory for architectural rules",
      keywords: ["python", "architecture", "memory"],
    });
    countTokens(prompt);
  });

  // Scenario 2: Memory Sliding Window (150 msgs -> 400 tok budget)
  bench("Memory Sliding Window (150 msgs -> 400 tok budget)", () => {
    const memory = new ShortTermMemory();
    for (let i = 0; i < 150; i++) {
      memory.set(`msg:${i}`, {
        role: i % 2 === 0 ? "user" : "assistant",
        content: `This is historical message number ${i} containing contextual information about task execution and system state.`,
      });
    }

    // Simulate sliding window extraction constrained by token budget
    let tokenCount = 0;
    const maxTokens = 400;
    const items: Array<{ key: string; tokens: number }> = [];

    for (let i = 149; i >= 0; i--) {
      const key = `msg:${i}`;
      const val = memory.get(key);
      if (!val) continue;
      const text = JSON.stringify(val);
      const tokens = countTokens(text);
      if (tokenCount + tokens > maxTokens) break;
      tokenCount += tokens;
      items.push({ key, tokens });
    }
  });

  // Scenario 3: Sandbox Extraction
  bench("Sandbox Extraction (QuickJS execution)", async () => {
    const code = `
      const data = JSON.parse(DATA);
      const result = data.messages
        .filter(m => m.role === 'user')
        .map(m => m.content.toUpperCase())
        .join(' | ');
      print(result);
    `;
    const data = JSON.stringify({
      messages: Array.from({ length: 50 }, (_, i) => ({
        role: i % 2 === 0 ? "user" : "assistant",
        content: `Message snippet ${i} with key data points to extract`,
      })),
    });

    await executeInSandbox(code, { data, language: "javascript" });
  });
});

// Helper run for generating the log artifact
